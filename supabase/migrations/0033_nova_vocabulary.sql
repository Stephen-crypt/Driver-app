drop function if exists public.trip_driver_position(p_trip_id uuid);
CREATE OR REPLACE FUNCTION public.trip_rider_position(p_trip_id uuid)
 RETURNS TABLE(lng double precision, lat double precision, recorded_at timestamp with time zone, metres_away double precision, eta_seconds integer)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_trip   public.trips;
  v_target geography;
begin
  select * into v_trip from public.trips where id = p_trip_id;
  if not found then
    return;
  end if;

  -- Both sides of a trip may see it; nobody else may.
  if v_trip.passenger_id <> auth.uid() and v_trip.rider_id is distinct from auth.uid() then
    return;
  end if;

  if v_trip.state not in ('accepted', 'arrived', 'in_progress') then
    return;
  end if;

  -- Before the passenger is aboard the rider is heading to the pickup; after, to
  -- the drop-off. The distance shown should be to wherever they are going.
  v_target := case
    when v_trip.state = 'in_progress' then v_trip.dropoff
    else v_trip.pickup
  end;

  return query
  select st_x(t.position::geometry),
         st_y(t.position::geometry),
         t.recorded_at,
         st_distance(t.position, v_target),
         -- 7.5 m/s is the same average the fare quote uses. One number, one
         -- meaning, rather than a second speed constant living here.
         greatest(30, (st_distance(t.position, v_target) / 7.5))::integer
    from public.trip_track_points t
   where t.trip_id = p_trip_id
   order by t.recorded_at desc
   limit 1;
end;
$function$;

drop function if exists public.trip_transition(p_trip_id uuid, p_to trip_state, p_idempotency_key text, p_meta jsonb);
CREATE OR REPLACE FUNCTION public.trip_transition(p_trip_id uuid, p_to trip_state, p_idempotency_key text, p_meta jsonb DEFAULT '{}'::jsonb)
 RETURNS trips
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_trip  public.trips;
  v_actor trip_actor;
begin
  select * into v_trip from public.trips where id = p_trip_id for update;
  if not found then
    raise exception 'trip_not_found' using errcode = 'P0002';
  end if;

  if v_trip.passenger_id = auth.uid() then
    v_actor := 'passenger';
  elsif v_trip.rider_id = auth.uid() then
    v_actor := 'rider';
  else
    raise exception 'not_a_participant' using errcode = '42501';
  end if;

  if exists (
    select 1 from public.trip_events
     where trip_id = p_trip_id and idempotency_key = p_idempotency_key
  ) then
    return v_trip;
  end if;

  if not public.is_legal_transition(v_trip.state, p_to, v_actor) then
    raise exception 'illegal_transition: % -> % by %', v_trip.state, p_to, v_actor
      using errcode = '23514';
  end if;

  insert into public.trip_events
    (trip_id, from_state, to_state, actor, actor_id, idempotency_key, meta)
  values
    (p_trip_id, v_trip.state, p_to, v_actor, auth.uid(), p_idempotency_key, p_meta);

  perform set_config('gera.in_transition', '1', true);

  update public.trips
     set state = p_to, updated_at = now()
   where id = p_trip_id
  returning * into v_trip;

  perform set_config('gera.in_transition', '0', true);

  return v_trip;
end;
$function$;

