-- NOVA vocabulary.
--
-- NOVA names the customer a Passenger and the driver a Rider. This schema named
-- the customer a rider and the driver a driver, so the two words swap places.
--
-- Done in one migration on purpose. A half-finished rename leaves `rider`
-- meaning the customer in one function and the driver in the next, and the first
-- bug that causes is an RLS policy handing someone else's location to the wrong
-- person. Every function body is recreated here because Postgres stores them as
-- text and re-resolves names at execution: a column rename alone would leave
-- them parsing fine and failing at runtime.
--
-- Generated by scripts/gen-nova-rename.mjs.

