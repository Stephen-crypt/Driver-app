drop function if exists public.complete_trip(p_trip_id uuid, p_actual_distance_m integer, p_idempotency_key text);
CREATE OR REPLACE FUNCTION public.complete_trip(p_trip_id uuid, p_actual_distance_m integer, p_idempotency_key text)
 RETURNS trips
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_trip       public.trips;
  v_policy     public.fare_policies;
  v_total      integer;
  v_commission integer;
begin
  -- Argument validation before the lock, as in 0013.
  if p_actual_distance_m is null or p_actual_distance_m < 0 then
    raise exception 'negative_distance' using errcode = '22023';
  end if;

  select * into v_trip from public.trips where id = p_trip_id for update;
  if not found then
    raise exception 'trip_not_found' using errcode = 'P0002';
  end if;

  -- Authorization BEFORE the idempotent early return. An unchecked early return
  -- on a security-definer function hands the whole trip row - passenger_id, both
  -- labels, and the free-text pickup_note - to anyone who supplies a trip id and
  -- a used idempotency key. Migration 0006 guards trip_transition() the same way
  -- and for the same reason. Only the rider may complete a trip.
  if v_trip.rider_id is null or v_trip.rider_id <> auth.uid() then
    raise exception 'not_the_rider' using errcode = '42501';
  end if;

  -- Idempotent: a replayed completion must not debit commission twice.
  if exists (
    select 1 from public.trip_events
     where trip_id = p_trip_id and idempotency_key = p_idempotency_key
  ) then
    return v_trip;
  end if;

  -- The locked price is the trip's own, written at creation from the quote. A
  -- trip with no quote has no price to honour, and inventing one is how a passenger
  -- gets charged a number nobody quoted them.
  if v_trip.quoted_amount_rwf is null or v_trip.quote_id is null then
    raise exception 'trip_has_no_quote' using errcode = '22023';
  end if;

  -- Priced under the policy the trip was QUOTED under, never the one in force
  -- now: a rate change between quote and completion must not reach this trip.
  select * into v_policy from public.fare_policy_for_quote(v_trip.quote_id);
  if v_policy.id is null then
    raise exception 'quote_policy_not_found' using errcode = '22023';
  end if;

  v_total := public.final_fare_rwf(
    v_trip.quoted_amount_rwf,
    coalesce(v_trip.quoted_distance_m, 0),
    p_actual_distance_m,
    v_policy.per_km_rwf
  );
  v_commission := public.commission_rwf(v_total, v_policy.commission_pct);

  perform set_config('gera.in_transition', '1', true);
  update public.trips
     set actual_distance_m = p_actual_distance_m
   where id = p_trip_id;
  perform set_config('gera.in_transition', '0', true);

  -- Raises if the edge is illegal or the caller is not the rider.
  v_trip := public.trip_transition(
    p_trip_id, 'completed', p_idempotency_key,
    jsonb_build_object(
      'total_rwf', v_total,
      'commission_rwf', v_commission,
      'policy_id', v_policy.id
    )
  );

  insert into public.ledger_entries (rider_id, trip_id, kind, amount_rwf, memo)
  values (v_trip.rider_id, p_trip_id, 'commission_debit', v_commission,
          'commission on trip ' || p_trip_id);

  return v_trip;
end;
$function$;

drop function if exists public.create_trip_from_quote(p_quote_id uuid, p_pickup geography, p_pickup_label text, p_pickup_note text, p_dropoff geography, p_dropoff_label text);
CREATE OR REPLACE FUNCTION public.create_trip_from_quote(p_quote_id uuid, p_pickup geography, p_pickup_label text, p_pickup_note text, p_dropoff geography, p_dropoff_label text)
 RETURNS trips
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_quote public.fare_quotes;
  v_trip  public.trips;
begin
  if auth.uid() is null then
    raise exception 'unauthenticated' using errcode = '42501';
  end if;

  select * into v_quote from public.fare_quotes where id = p_quote_id;
  if not found then
    raise exception 'quote_not_found' using errcode = 'P0002';
  end if;

  if v_quote.passenger_id <> auth.uid() then
    raise exception 'quote_not_yours' using errcode = '42501';
  end if;

  if v_quote.expires_at <= now() then
    raise exception 'quote_expired' using errcode = '22023';
  end if;

  insert into public.trips
    (passenger_id, vehicle_class, state, pickup, pickup_label, pickup_note,
     dropoff, dropoff_label, quoted_distance_m, quoted_duration_s,
     quote_id, quoted_amount_rwf)
  values
    (auth.uid(), v_quote.vehicle_class, 'requested', p_pickup, p_pickup_label,
     nullif(btrim(coalesce(p_pickup_note, '')), ''),
     p_dropoff, p_dropoff_label, v_quote.distance_m, v_quote.duration_s,
     v_quote.id, v_quote.amount_rwf)
  returning * into v_trip;

  return v_trip;
end;
$function$;

drop function if exists public.create_trip_offer(p_trip_id uuid, p_driver_id uuid, p_rank integer, p_eta_seconds integer, p_ttl_seconds integer, p_idempotency_key text);
CREATE OR REPLACE FUNCTION public.create_trip_offer(p_trip_id uuid, p_rider_id uuid, p_rank integer, p_eta_seconds integer, p_ttl_seconds integer, p_idempotency_key text)
 RETURNS trip_offers
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_offer public.trip_offers;
begin
  if p_ttl_seconds <= 0 then
    raise exception 'ttl_must_be_positive' using errcode = '22023';
  end if;

  perform 1 from public.trips where id = p_trip_id for update;
  if not found then
    raise exception 'trip_not_found' using errcode = 'P0002';
  end if;

  -- Idempotent: a retried dispatch must not create a second live offer. LIVE,
  -- not merely unresolved - see the note above.
  select * into v_offer from public.trip_offers
   where trip_id = p_trip_id and outcome is null and expires_at > now();
  if found then
    return v_offer;
  end if;

  if exists (
    select 1 from public.trip_offers
     where rider_id = p_rider_id and outcome is null
  ) then
    raise exception 'rider_already_offered' using errcode = '42501';
  end if;

  if exists (
    select 1 from public.trips
     where rider_id = p_rider_id
       and id <> p_trip_id
       and state in ('offered', 'accepted', 'arrived', 'in_progress')
  ) then
    raise exception 'rider_already_committed' using errcode = '42501';
  end if;

  insert into public.trip_offers (trip_id, rider_id, rank, eta_seconds, expires_at)
  values (p_trip_id, p_rider_id, p_rank, p_eta_seconds,
          now() + make_interval(secs => p_ttl_seconds))
  returning * into v_offer;

  perform public.assign_rider_to_trip(p_trip_id, p_rider_id, p_idempotency_key);

  return v_offer;
end;
$function$;

