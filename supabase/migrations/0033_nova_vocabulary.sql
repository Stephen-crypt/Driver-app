drop function if exists public.assign_driver_to_trip(p_trip_id uuid, p_driver_id uuid, p_idempotency_key text);
CREATE OR REPLACE FUNCTION public.assign_rider_to_trip(p_trip_id uuid, p_rider_id uuid, p_idempotency_key text)
 RETURNS trips
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_trip public.trips;
begin
  select * into v_trip from public.trips where id = p_trip_id for update;
  if not found then
    raise exception 'trip_not_found' using errcode = 'P0002';
  end if;

  if not exists (
    select 1 from public.riders
     where id = p_rider_id and verification = 'verified'
  ) then
    raise exception 'rider_not_verified' using errcode = '42501';
  end if;

  -- The replay check has to happen HERE, before the rider_id write, not inside
  -- trip_transition_system() afterwards. The lock taken above is what makes it
  -- race-safe, exactly as in trip_transition().
  if exists (
    select 1 from public.trip_events
     where trip_id = p_trip_id and idempotency_key = p_idempotency_key
  ) then
    return v_trip;
  end if;

  perform set_config('gera.in_transition', '1', true);
  update public.trips set rider_id = p_rider_id where id = p_trip_id;
  perform set_config('gera.in_transition', '0', true);

  -- The rider goes into the event meta: an offer log that does not record who
  -- was offered the trip cannot answer the one question it exists to answer.
  return public.trip_transition_system(
    p_trip_id, 'offered', p_idempotency_key,
    jsonb_build_object('rider_id', p_rider_id)
  );
end;
$function$;

