drop function if exists public.rate_trip(p_trip_id uuid, p_rating smallint, p_comment text);
CREATE OR REPLACE FUNCTION public.rate_trip(p_trip_id uuid, p_rating smallint, p_comment text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_trip     public.trips;
  v_previous smallint;
begin
  if p_rating is null or p_rating < 1 or p_rating > 5 then
    raise exception 'rating_out_of_range' using errcode = '22023';
  end if;

  -- Authorise BEFORE reading anything back, and answer identically for "no
  -- such trip" and "not your trip" - the lookup-oracle defect this project has
  -- shipped twice already.
  select * into v_trip from public.trips where id = p_trip_id;
  if not found or v_trip.passenger_id <> auth.uid() then
    raise exception 'trip_not_found' using errcode = 'P0002';
  end if;

  if v_trip.state <> 'completed' then
    raise exception 'trip_not_completed' using errcode = '22023';
  end if;
  if v_trip.rider_id is null then
    raise exception 'trip_has_no_rider' using errcode = '22023';
  end if;

  select rating into v_previous from public.trip_ratings where trip_id = p_trip_id;

  insert into public.trip_ratings (trip_id, passenger_id, rider_id, rating, comment)
  values (p_trip_id, v_trip.passenger_id, v_trip.rider_id, p_rating, p_comment)
  on conflict (trip_id) do update
    set rating = excluded.rating,
        comment = excluded.comment,
        created_at = now();

  if v_previous is null then
    update public.riders
       set rating_sum = rating_sum + p_rating,
           rating_count = rating_count + 1
     where id = v_trip.rider_id;
  else
    -- A correction moves the sum by the difference. Adding again would let a
    -- passenger inflate a rider by re-rating.
    update public.riders
       set rating_sum = rating_sum + (p_rating - v_previous)
     where id = v_trip.rider_id;
  end if;
end;
$function$;

drop function if exists public.register_driver(p_first_name text, p_phone text, p_licence text, p_plate text, p_vest text, p_class vehicle_class);
CREATE OR REPLACE FUNCTION public.register_rider(p_first_name text, p_phone text, p_licence text, p_plate text, p_vest text, p_class vehicle_class)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  insert into public.profiles (id, role, first_name, phone)
  values (v_uid, 'rider', p_first_name, p_phone)
  on conflict (id) do update
     set role       = 'rider',
         first_name = excluded.first_name,
         phone      = excluded.phone,
         updated_at = now();

  -- `verification` is hardcoded and is deliberately NOT a parameter. Ops owns
  -- that value; a caller who could pass it would register themselves verified
  -- and walk straight into the dispatch index. An existing row keeps whatever
  -- verification ops already gave it - a re-submit must not silently demote a
  -- rider who is already approved, nor promote one who is not.
  insert into public.riders (id, verification, licence_number)
  values (v_uid, 'submitted', p_licence)
  on conflict (id) do update
     set licence_number = excluded.licence_number,
         updated_at     = now();

  insert into public.vehicles (rider_id, class, plate, vest_number, is_active)
  values (v_uid, p_class, p_plate, p_vest, false)
  on conflict (rider_id, plate) do update
     set class       = excluded.class,
         vest_number = excluded.vest_number;
end;
$function$;

