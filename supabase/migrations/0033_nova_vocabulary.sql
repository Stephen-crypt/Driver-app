    -- caller cannot tell one from the other.
    return;
  end if;

  if v_rider is null then
    return;
  end if;

  return query
  select p.first_name,
         v.plate,
         v.vest_number,
         v.class,
         case when d.rating_count > 0
              then round(d.rating_sum::numeric / d.rating_count, 1)
              else null
         end
    from public.profiles p
    join public.riders d on d.id = p.id
    left join public.vehicles v on v.rider_id = p.id and v.is_active
   where p.id = v_rider;
