drop function if exists public.trip_driver_card(p_trip_id uuid);
CREATE OR REPLACE FUNCTION public.trip_rider_card(p_trip_id uuid)
 RETURNS TABLE(first_name text, plate text, vest_number text, vehicle_class vehicle_class, rating numeric)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_passenger  uuid;
  v_rider uuid;
begin
  -- Authorise FIRST, and on the trip, not on the rider. Returning early on a
  -- missing rider before checking the caller is how a security definer
  -- function turns into a lookup oracle - the exact defect this project
  -- shipped twice, in trip_transition and complete_trip.
  select t.passenger_id, t.rider_id into v_passenger, v_rider
    from public.trips t where t.id = p_trip_id;

  if v_passenger is null or v_passenger <> auth.uid() then
