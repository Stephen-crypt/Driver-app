drop function if exists public.find_candidate_drivers(p_pickup geography, p_class vehicle_class, p_radius_m integer, p_limit integer);
CREATE OR REPLACE FUNCTION public.find_candidate_riders(p_pickup geography, p_class vehicle_class, p_radius_m integer, p_limit integer)
 RETURNS TABLE(rider_id uuid, distance_m double precision)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select p.rider_id,
         st_distance(p.position, p_pickup) as distance_m
    from public.rider_presence p
    join public.riders d on d.id = p.rider_id
   where p.status = 'online'
     and p.vehicle_class = p_class
     and p.position is not null
     -- A rider whose app died must not be offered a trip. Spec 6: the server
     -- decides a rider is gone, never the client.
     and p.heartbeat_at > now() - interval '30 seconds'
     and d.verification = 'verified'
     -- Spec 3.5, enforced at the point of dispatch rather than only at the
     -- moment of going online. A rider whose wallet fell below the minimum
     -- mid-shift stops being dispatchable immediately, whether or not they ever
     -- write `status` again.
     and public.can_go_online_internal(p.rider_id)
     and st_dwithin(p.position, p_pickup, p_radius_m)
     -- Not already committed to another live trip.
     and not exists (
       select 1 from public.trips t
        where t.rider_id = p.rider_id
          and t.state in ('offered', 'accepted', 'arrived', 'in_progress')
     )
   order by st_distance(p.position, p_pickup)
   limit p_limit;
$function$;

