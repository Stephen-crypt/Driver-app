// Generates the NOVA vocabulary migration.
//
// NOVA calls the customer a Passenger and the driver a Rider. This codebase
// called the customer a rider and the driver a driver, so the two words must
// SWAP - and a naive sequential replace collides: rename rider->passenger first
// and the later driver->rider is fine, but do it the other way and every driver
// becomes a passenger. Both orders are wrong for at least one identifier, so the
// swap goes through a placeholder.
//
// Generated rather than hand-written because it touches 49 function bodies, and
// a rename that is 95% done is far more dangerous than one not started: code
// where `rider` means the customer in one file and the driver in the next
// produces authorisation bugs that read as correct.
//
//   node scripts/gen-nova-rename.mjs > supabase/migrations/0033_nova_vocabulary.sql
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const DB = process.env.GERA_DB_CONTAINER ?? "supabase_db_driver_app";
const TMP = process.env.TEMP ?? "/tmp";

const psql = (sql) =>
  execFileSync("docker", [
    "exec", DB, "psql", "-U", "postgres", "-d", "postgres", "-tA", "-c", sql,
  ]).toString().trim();

/**
 * The swap. `driving_licence` is protected: it is a document kind, not a role,
 * and "riding_licence" is not a thing.
 */
export function swap(text) {
  return text
    .replace(/driving_licence/g, "\u0001DRIVLIC\u0001")
    .replace(/DRIVING_LICENCE/g, "\u0001DRIVLICU\u0001")
    // rider -> placeholder
    .replace(/rider/g, "\u0002pass\u0002")
    .replace(/Rider/g, "\u0002Pass\u0002")
    .replace(/RIDER/g, "\u0002PASS\u0002")
    // driver -> rider
    .replace(/driver/g, "rider")
    .replace(/Driver/g, "Rider")
    .replace(/DRIVER/g, "RIDER")
    // placeholder -> passenger
    .replace(/\u0002pass\u0002/g, "passenger")
    .replace(/\u0002Pass\u0002/g, "Passenger")
    .replace(/\u0002PASS\u0002/g, "PASSENGER")
    .replace(/\u0001DRIVLIC\u0001/g, "driving_licence")
    .replace(/\u0001DRIVLICU\u0001/g, "DRIVING_LICENCE");
}

const out = [];
const say = (s) => out.push(s);

say(`-- NOVA vocabulary.
--
-- NOVA names the customer a Passenger and the driver a Rider. This schema named
-- the customer a rider and the driver a driver, so the two words swap places.
--
-- Done in one migration on purpose. A half-finished rename leaves \`rider\`
-- meaning the customer in one function and the driver in the next, and the first
-- bug that causes is an RLS policy handing someone else's location to the wrong
-- person. Every function body is recreated here because Postgres stores them as
-- text and re-resolves names at execution: a column rename alone would leave
-- them parsing fine and failing at runtime.
--
-- Generated by scripts/gen-nova-rename.mjs.

-- 1. Enum values. Order matters: the customer's value must vacate the name
-- \`rider\` before the driver's value can take it.
alter type user_role rename value 'rider' to 'passenger';
alter type user_role rename value 'driver' to 'rider';

alter type trip_state rename value 'cancelled_by_rider' to 'cancelled_by_passenger';
alter type trip_state rename value 'cancelled_by_driver' to 'cancelled_by_rider';

alter type sos_source rename value 'rider' to 'passenger';
alter type sos_source rename value 'driver' to 'rider';

alter type trip_actor rename value 'rider' to 'passenger';
alter type trip_actor rename value 'driver' to 'rider';

-- This type's NAME carries the old vocabulary even though its values do not.
alter type driver_status rename to rider_status;

alter type trip_state rename value 'no_drivers' to 'no_riders';

-- Not caught by the column sweep because it is not named driver_id, but the
-- function bodies below already say min_rider_balance_rwf - without this they
-- parse and then fail at call time, which check_function_bodies = off would
-- have let through silently.
alter table public.platform_settings
  rename column min_driver_balance_rwf to min_rider_balance_rwf;

-- 1b. Two policies call functions that are recreated further down, and Postgres
-- refuses to drop a function a policy depends on. They come off here and go
-- back on at the end, with their expressions swapped.
drop policy presence_owner_all on public.driver_presence;
drop policy profiles_select_trip_partner on public.profiles;

-- 2. Tables.
alter table public.drivers rename to riders;
alter table public.driver_presence rename to rider_presence;
alter table public.driver_documents rename to rider_documents;

-- 3. Columns. Same ordering rule as the enums: within one table the customer
-- column must be renamed before the driver column claims its name.
alter table public.trips rename column rider_id to passenger_id;
alter table public.trips rename column driver_id to rider_id;

alter table public.trip_ratings rename column rider_id to passenger_id;
alter table public.trip_ratings rename column driver_id to rider_id;

alter table public.fare_quotes rename column rider_id to passenger_id;
alter table public.saved_places rename column rider_id to passenger_id;

alter table public.rider_presence rename column driver_id to rider_id;
alter table public.rider_documents rename column driver_id to rider_id;
alter table public.ledger_entries rename column driver_id to rider_id;
alter table public.trip_offers rename column driver_id to rider_id;
alter table public.vehicles rename column driver_id to rider_id;
`);

// ---------------------------------------------------------------------------
// 4. Indexes and constraints. Purely cosmetic - nothing references them by name
// - but a schema where half the identifiers say driver is the state this
// migration exists to avoid.
const indexes = psql(`
  select indexname from pg_indexes
   where schemaname='public' and (indexname ~ 'driver' or indexname ~ 'rider')
   order by indexname;`)
  .split("\n").filter(Boolean);

// Two ordered passes, for the same reason the enums needed one: renaming
// trips_driver_idx to trips_rider_idx collides with the trips_rider_idx that
// already exists, until that one has moved aside.
const renameIn = (names, label) => {
  for (const name of names) {
    const next = swap(name);
    if (next !== name) say(`alter ${label} public.${name} rename to ${next};`);
  }
};

if (indexes.length) {
  say("\n-- 4. Indexes, customer-named ones first so their names are free.");
  renameIn(indexes.filter((i) => /rider/.test(i)), "index");
  renameIn(indexes.filter((i) => /driver/.test(i) && !/rider/.test(i)), "index");
}

const policies = psql(`
  select tablename || '|' || policyname from pg_policies
   where schemaname='public' and (policyname ~ 'driver' or policyname ~ 'rider')
   order by 1;`)
  .split("\n").filter(Boolean);

if (policies.length) {
  say("\n-- 5. Policy names, in the same two passes. The expressions follow the\n-- column renames above automatically; only the names need moving.");
  const renamePolicy = (row) => {
    const [table, policy] = row.split("|");
    const nextTable = swap(table);
    const nextPolicy = swap(policy);
    if (nextPolicy !== policy) {
      say(`alter policy ${policy} on public.${nextTable} rename to ${nextPolicy};`);
    }
  };
  policies.filter((r) => /rider/.test(r.split("|")[1])).forEach(renamePolicy);
  policies
    .filter((r) => /driver/.test(r.split("|")[1]) && !/rider/.test(r.split("|")[1]))
    .forEach(renamePolicy);
}

// ---------------------------------------------------------------------------
// 6. Functions. Bodies are text, so every one that mentions a renamed object
// has to be recreated. Where the function's own name changes, the old one is
// dropped and its grants re-applied.
const defs = readFileSync(`${TMP}/rename/functions.sql`, "utf8")
  .split("-- ##SPLIT##")
  .map((s) => s.trim())
  .filter(Boolean);

// Identity args for EVERY function, not only the granted ones: a function with
// no grants can still have a parameter whose name changes, and CREATE OR REPLACE
// cannot rename a parameter.
const signatures = new Map(
  readFileSync(`${TMP}/rename/sigs.txt`, "utf8")
    .split(String.fromCharCode(10))
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line) => {
      const i = line.indexOf("|");
      return [line.slice(0, i), line.slice(i + 1)];
    }),
);

const grants = readFileSync(`${TMP}/rename/grants.txt`, "utf8")
  .split(/\r?\n/).filter(Boolean)
  .map((line) => {
    const [sig, role] = line.split("|");
    return { sig, role };
  });

say(`
-- 6. Function bodies.
--
-- check_function_bodies off for this section: the functions are recreated in
-- alphabetical order, so can_go_online_internal is rebuilt before the
-- rider_balance_internal it calls exists under its new name. Postgres validates
-- a SQL function's body at creation and would reject it. Turning the check off
-- lets them be created in any order and resolve at call time; it is restored
-- immediately afterwards, and the pgTAP suite is what proves they all still
-- resolve.
set local check_function_bodies = off;`);

const renamedSignatures = [];

for (const def of defs) {
  const next = swap(def);
  if (next === def) continue;

  // CREATE OR REPLACE cannot change a function's name, and it cannot change
  // argument names either - both need the old one dropped first.
  const nameMatch = def.match(/CREATE OR REPLACE FUNCTION public\.([a-z0-9_]+)\(/i);
  if (!nameMatch) continue;
  const oldName = nameMatch[1];

  const identity = signatures.get(oldName) ?? null;

  // A drop is only needed when the SIGNATURE moves - a different name, or
  // different parameter names, neither of which CREATE OR REPLACE can do.
  // Where only the body changes, replacing in place matters: trigger functions
  // and policy-referenced functions cannot be dropped at all while the trigger
  // or policy that depends on them exists.
  // CREATE OR REPLACE cannot change a function's name, its parameter names, OR
  // the column names of a RETURNS TABLE - and this rename touches all three. So
  // everything is dropped and recreated, EXCEPT trigger functions: Postgres
  // refuses to drop one while its trigger exists, and their signatures never
  // change here because none of them carries a role word.
  const isTrigger = /RETURNS trigger/i.test(def);

  if (!isTrigger) {
    if (identity) {
      say(`\ndrop function if exists public.${oldName}${identity};`);
    } else {
      say(`\ndrop function if exists public.${oldName} cascade;`);
    }
  } else {
    say(`\n-- ${oldName}: body only, replaced in place.`);
  }

  say(next.endsWith(";") ? next : `${next};`);
  renamedSignatures.push({ oldName, identity });
}

// ---------------------------------------------------------------------------
// 7. Grants, re-applied under the new names. A dropped function takes its
// grants with it, and a function nobody can execute is a silent outage.
say("\nset local check_function_bodies = on;");

// PUBLIC first, and this is the whole point of the section. Postgres grants
// EXECUTE on a newly created function to PUBLIC by default, and anon inherits
// from PUBLIC - so `revoke ... from anon` reports REVOKE and changes nothing.
// Verified on the live database: anon still held trip_transition after its
// revoke ran. Every recreated function starts closed and is reopened only to
// the roles that held it before the rename.
say("\n-- 7. Close every recreated function to PUBLIC before reopening any of it.");
for (const [name, args] of signatures) {
  say(`revoke all on function public.${swap(name + args)} from public;`);
}

say("\n-- 7b. Grants, re-applied to the recreated functions.");
const seen = new Set();
for (const { sig, role } of grants) {
  const next = swap(sig);
  const key = `${next}|${role}`;
  if (seen.has(key)) continue;
  seen.add(key);
  say(`grant execute on function public.${next} to ${role};`);
}

// Nothing that was locked away should come back open.
say(`
-- 8. Re-assert the revokes. Supabase grants \`authenticated\` privileges through
-- ALTER DEFAULT PRIVILEGES, so a recreated function can come back executable by
-- roles that were deliberately denied it - the defect this project has already
-- shipped four times.`);

// The parentheses come from the query, not from reassembling the string here:
// a name and its arguments run together with no separator, so any regex that
// tries to split them swallows the first parameter into the function name.
const revokes = psql(`
  select p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')|' || r.rolname
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    cross join lateral (select rolname from pg_roles where rolname in ('anon','authenticated')) r
   where n.nspname='public' and p.prokind='f'
     and p.oid not in (select objid from pg_depend where deptype='e')
     and not has_function_privilege(r.rolname, p.oid, 'EXECUTE')
   order by 1;`)
  .split("\n").filter(Boolean);

for (const row of revokes) {
  const [sig, role] = row.split("|");
  say(`revoke all on function public.${swap(sig)} from ${role};`);
}

// The policies dropped up front, restored now that the functions they call
// exist again under their new names.
say(`
-- 9. Policies restored.
create policy presence_owner_all on public.rider_presence
  for all
  using (rider_id = auth.uid())
  with check (
    rider_id = auth.uid()
    and (
      status <> 'online'::rider_status
      or presence_status_now(auth.uid()) = 'online'::rider_status
      or (
        exists (
          select 1 from public.riders d
           where d.id = auth.uid() and d.verification = 'verified'::verification_status
        )
        and can_go_online(auth.uid())
      )
    )
  );

create policy profiles_select_trip_partner on public.profiles
  for select
  using (shares_active_trip(id));`);

// The documents bucket is a ROW in storage.buckets, not a schema object, so
// none of the renames above reached it. Moved by creating the new bucket,
// carrying the objects across and dropping the old one - rather than updating
// a primary key that storage.objects has a foreign key onto.
say(`
-- 10. Storage: the documents bucket and its policies.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
select 'rider-documents', 'rider-documents', public, file_size_limit, allowed_mime_types
  from storage.buckets where id = 'driver-documents'
on conflict (id) do nothing;

update storage.objects set bucket_id = 'rider-documents' where bucket_id = 'driver-documents';

-- The old bucket is deliberately left in place, empty. Supabase refuses a
-- direct DELETE from storage.buckets ("Use the Storage API instead"), and an
-- empty bucket nothing references is a tidiness problem, not a correctness one.
-- Remove it from the dashboard if it bothers you.

-- The policies name the bucket as a literal, so they have to be rewritten
-- rather than renamed.
drop policy if exists driver_docs_insert_own on storage.objects;
drop policy if exists driver_docs_select_own on storage.objects;
drop policy if exists driver_docs_update_own on storage.objects;

create policy rider_docs_insert_own on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'rider-documents'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy rider_docs_select_own on storage.objects
  for select to authenticated
  using (
    bucket_id = 'rider-documents'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy rider_docs_update_own on storage.objects
  for update to authenticated
  using (
    bucket_id = 'rider-documents'
    and (storage.foldername(name))[1] = auth.uid()::text
  );`);

process.stdout.write(out.join("\n") + "\n");
